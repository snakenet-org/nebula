// @ai-purpose: Client-side parser/formatter for the Project view's .env upload + download flows.
// @ai-context: Parsing happens entirely client-side, before anything is sent to the bulk-create API
//   (nebula.secrets.create_keys_bulk) — the backend still independently re-checks for duplicate
//   names, this module's only job is turning raw file text into name/value pairs. Comments (a line
//   whose first non-whitespace character is `#`) and blank lines are stripped first, per spec —
//   deliberately NOT stripping a trailing `# ...` after a value on the same line, since that's
//   ambiguous with a value that legitimately contains `#` (quoted or not) and the spec only asked to
//   remove comment LINES. Every remaining line must match `KEY=VALUE` (optionally `export KEY=VALUE`,
//   a common shell/.env convention) or the whole file is rejected — parseEnvFile never returns a
//   partial result, matching the "fail if a single line can't be parsed" requirement.
//   formatEnvFile (2026-08-12) is the inverse direction, backing "Download .env" — it never exports
//   an actual secret/variable value (this module has no access to decrypted plaintext anyway; the
//   caller only ever passes it the already-loaded key list, never a revealed value). Each key
//   becomes `${nebula.<project>.<environment>.<key>}`, the exact cross-project reference syntax
//   nebula-cli's own `deploy` command already parses and resolves (confirmed against that sibling
//   repo's README, not invented fresh here) — so the downloaded file is meant to be committed as a
//   stack-file template, not filled in with real secrets. Project/Environment/SecretKey names are
//   all charset-restricted to `[A-Za-z0-9_-]+` (nebula.naming.NAME_PATTERN, enforced server-side),
//   so none of the three ever needs escaping/quoting when substituted into that marker.
//   2026-08-12 (later same day): output is now a single line break between entries, not a blank
//   line — each key was already at most two lines (an optional `# <description>` line + the
//   `KEY=${...}` line), so the blank separator only made a short file look sparser, not more
//   readable. Also gained a leading header comment block (`# Generated by Nebula Vault v<version>
//   on <date>`) — `version` is a new required param, sourced by the caller from
//   `useConfig().state.config.version` (the same value App.vue's footer already shows), since this
//   module has no access to the composable/API layer itself. `generatedAt` defaults to `new Date()`
//   so callers don't need to pass it explicitly; it's a param only so a test can pin it.
// @version: 1.2.0
// @author: Marc Fiedler <marc@snakenet.org>
// @date: 2026-08-12

// KEY must look like a shell/env identifier: letters, digits, underscore, not starting with a digit.
const LINE_RE = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/;

function unquoteValue(raw) {
  const trimmed = raw.trim();
  if (trimmed.length >= 2) {
    const first = trimmed[0];
    const last = trimmed[trimmed.length - 1];
    if (first === '"' && last === '"') {
      return trimmed
        .slice(1, -1)
        .replace(/\\n/g, '\n')
        .replace(/\\"/g, '"')
        .replace(/\\\\/g, '\\');
    }
    if (first === "'" && last === "'") {
      return trimmed.slice(1, -1);
    }
  }
  return trimmed;
}

/**
 * Parses .env-formatted text into name/value pairs.
 * Returns { items: [{ name, value }], errors: [{ line, content }] } — `errors` is only ever
 * non-empty when at least one non-comment, non-blank line didn't match `KEY=VALUE`; callers should
 * treat any non-empty `errors` as "reject the whole upload," not attempt to use `items` alongside it.
 */
export function parseEnvFile(text) {
  const items = [];
  const errors = [];
  const seenNames = new Set();
  const rawLines = text.split(/\r\n|\r|\n/);

  for (let i = 0; i < rawLines.length; i++) {
    const line = rawLines[i];
    const trimmed = line.trim();
    if (trimmed === '' || trimmed.startsWith('#')) continue;

    const match = LINE_RE.exec(trimmed);
    if (!match) {
      errors.push({ line: i + 1, content: line });
      continue;
    }
    const name = match[1];
    const value = unquoteValue(match[2]);
    if (!seenNames.has(name.toLowerCase())) {
      seenNames.add(name.toLowerCase());
      items.push({ name, value });
    } else {
      // Keep the LAST value for a name repeated within the same file (standard .env/shell semantics
      // — a later line overrides an earlier one) rather than failing the whole upload over it.
      const idx = items.findIndex((item) => item.name.toLowerCase() === name.toLowerCase());
      items[idx] = { name, value };
    }
  }

  return { items, errors };
}

/**
 * Builds .env-formatted export text for a Project's keys — the inverse of parseEnvFile. Starts with
 * a `# Generated by Nebula Vault v<version> on <date>` header comment, then each key becomes an
 * optional `# <description>` comment line (omitted when the key has none) followed by
 * `KEY=${nebula.<project>.<environment>.KEY}` — every line separated by a single line break, no
 * blank lines between entries. `projectName` and each `key.environment_name`/`key.name` are
 * substituted verbatim (see the header comment for why that's always safe).
 */
export function formatEnvFile(projectName, keys, version, generatedAt = new Date()) {
  const lines = [`# Generated by Nebula Vault v${version} on ${generatedAt.toISOString()}`];
  for (const key of keys) {
    if (key.description) lines.push(`# ${key.description}`);
    lines.push(`${key.name}=\${nebula.${projectName}.${key.environment_name}.${key.name}}`);
  }
  return lines.join('\n');
}
